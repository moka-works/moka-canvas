//! Built-in extension node deployment.
//!
//! On startup, every built-in definition whose version is newer than the one
//! recorded in its deployed `node.json` is written out — the document and every
//! Lua file embedded beside it. A definition the reader customised carries a
//! version of its own, so it is left alone until a later built-in version
//! overtakes what it says. A directory the reader added is never this module's
//! to touch.

use std::path::Path;

/// One built-in definition, embedded at compile time.
pub struct NodeDef {
    pub id: &'static str,
    pub version: u64,
    pub document: &'static str,
    /// Every `.lua` beside the document, by filename.
    pub scripts: &'static [(&'static str, &'static str)],
}

// The built-in nodes, one per directory under `node-scripts/nodes`.
// Generated by `build.rs` rather than listed here, so shipping a definition is
// adding its directory and nothing else.
include!(concat!(env!("OUT_DIR"), "/builtin_nodes.rs"));

/// The version a deployed `node.json` records, zero when it does not say or
/// cannot be read — either way a built-in of any version may take its place.
fn deployed_version(path: &Path) -> u64 {
    std::fs::read_to_string(path)
        .ok()
        .and_then(|text| serde_json::from_str::<serde_json::Value>(&text).ok())
        .and_then(|value| value.get("version").and_then(serde_json::Value::as_u64))
        .unwrap_or(0)
}

/// Ensures every built-in definition is deployed under `root`, creating or
/// updating its directory as needed. Called once at startup.
pub async fn ensure_deployed(root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    for def in BUILTIN_NODES {
        let dir = root.join(def.id);
        if deployed_version(&dir.join("node.json")) >= def.version {
            continue;
        }
        tokio::fs::create_dir_all(&dir).await?;
        for (name, source) in def.scripts {
            tokio::fs::write(dir.join(name), source).await?;
        }
        // Written last, so a process that stops mid-deploy leaves the older
        // document saying a version the older scripts still satisfy rather
        // than a new document naming scripts that are not there yet.
        tokio::fs::write(dir.join("node.json"), def.document).await?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::extension::registry::ExtensionRegistry;

    #[test]
    fn every_built_in_definition_has_a_document_an_entry_script_and_a_version() {
        assert!(!BUILTIN_NODES.is_empty());
        let mut named = Vec::new();
        for def in BUILTIN_NODES {
            let document: serde_json::Value =
                serde_json::from_str(def.document).unwrap_or_else(|e| panic!("{}: {e}", def.id));
            assert!(def.version >= 1, "{}", def.id);
            assert!(!document["displayName"]
                .as_str()
                .unwrap_or_default()
                .is_empty());
            let entry = document["script"].as_str().unwrap_or_default();
            assert!(
                def.scripts.iter().any(|(name, _)| *name == entry),
                "{} names '{entry}', which is not embedded",
                def.id
            );
            assert!(!named.contains(&def.id), "{} is declared twice", def.id);
            named.push(def.id);
        }
    }

    #[tokio::test]
    async fn deploys_every_built_in_definition_so_the_registry_reads_it() {
        let dir = tempfile::tempdir().unwrap();
        ensure_deployed(dir.path()).await.unwrap();

        let registry = ExtensionRegistry::load(dir.path());
        assert!(registry.problems().is_empty(), "{:?}", registry.problems());
        for def in BUILTIN_NODES {
            assert!(
                registry.find(def.id).is_some(),
                "{} was not deployed",
                def.id
            );
        }
        // A second deploy finds every document already at its version.
        let before =
            std::fs::read_to_string(dir.path().join(BUILTIN_NODES[0].id).join("node.json"))
                .unwrap();
        ensure_deployed(dir.path()).await.unwrap();
        let after = std::fs::read_to_string(dir.path().join(BUILTIN_NODES[0].id).join("node.json"))
            .unwrap();
        assert_eq!(before, after);
    }

    #[tokio::test]
    async fn a_reader_customised_definition_survives_until_a_later_version_overtakes_it() {
        let dir = tempfile::tempdir().unwrap();
        ensure_deployed(dir.path()).await.unwrap();
        let def = &BUILTIN_NODES[0];
        let document = dir.path().join(def.id).join("node.json");
        std::fs::write(
            &document,
            format!(
                r#"{{"displayName": "Mine", "version": {}}}"#,
                def.version + 100
            ),
        )
        .unwrap();

        ensure_deployed(dir.path()).await.unwrap();
        let text = std::fs::read_to_string(&document).unwrap();
        assert!(text.contains("Mine"), "{text}");
    }
}
